"""Write src/geoblock_core/data/place_data_support.json: per catalogue place, the touchdown terrain and imagery
sources, their resolutions and a quality tier, for the app's place picker.

  cd scripts && python -m touchdown.place_data_support          # rewrite the JSON
  cd scripts && python -m touchdown.place_data_support --check  # exit 1 if the JSON is stale

Tier "fine": sub-metre aerial imagery at the landing and a DEM of 5 m or finer; "coarse" otherwise. The sources are
what the build would choose (geoblock_core.global_dem.plan, touchdown.aerial.pick; in the US the catalogued 3DEP
1 m project, else the 1/3 arc-second DEM, and NAIP). ``checked`` says where a source has actually been fetched
for real; a national server the cloud cannot reach stays "not yet fetched" until the desktop probe
(touchdown.global_data_check) has run.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from geoblock_core import global_dem  # noqa: E402
from geoblock_core.places import landing, places  # noqa: E402
from geoblock_core.utm import projected_crs  # noqa: E402
from touchdown import aerial  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "src" / "geoblock_core" / "data" / "place_data_support.json"

DEM_NAMES = {"swissalti3d": "swisstopo swissALTI3D", "ign-rgealti": "IGN RGE ALTI", "ign-lidarhd": "IGN LiDAR HD MNT (RGE ALTI where not yet released)",
             "es-mdt05": "IGN España MDT05", "tirol-dtm": "Land Tirol Geländemodell 0.5 m", "kartverket-dtm": "Kartverket DTM 1 m",
             "linz-dem1m": "LINZ national 1 m lidar DEM", "gsi-dem5": "GSI DEM5A/5B/5C",
             "glo30": "Copernicus DEM GLO-30 (surface model)", "usgs-3dep-1m": "USGS 3DEP 1 m lidar DEM",
             "usgs-3dep-13": "USGS 3DEP 1/3 arc-second DEM"}
DEM_CHECKED = {"usgs-3dep-1m": "used in production builds", "usgs-3dep-13": "used in production builds",
               "glo30": "fetched from the cloud, 18 Oct (global_data_check)",
               "linz-dem1m": "fetched from the cloud, 18 Oct (global_data_check: Milford Sound, 100% cover)"}
IMAGERY_CHECKED = {"naip": "used in production builds",
                   "ign-fr": "desktop dive, 11 Oct (aerial_check: Aiguille du Midi)",
                   "swissimage-ch": "desktop dive, 11 Oct (aerial_check: Gornergrat)",
                   "gsi-jp": "desktop dive, 11 Oct (aerial_check: Mount Fuji)",
                   "pnoa-es": "desktop dive, 11 Oct (aerial_check: Ronda)",
                   "pdok-nl": "desktop dive, 11 Oct (aerial_check: Kinderdijk)",
                   "linz-nz": "fetched from the cloud, 18 Oct (global_data_check: Milford Sound, 0.1 m)",
                   "s2-l2a": "fetched from the cloud, 18 Oct (global_data_check)"}
NOT_YET = "not yet fetched (run touchdown.global_data_check on the desktop)"


def tier(dem_m: float, imagery_m: float) -> str:
    return "fine" if imagery_m < 1.0 and dem_m <= 5.0 else "coarse"


def entry(place: dict) -> dict:
    lat, lon = landing(place)
    country = place.get("country", "")
    if country == "US":
        lidar = place.get("coverage", {}).get("dem1m", [])
        fine = lidar and lidar[0].get("project") != "3dep13"  # "3dep13": the 1/3" DEM by name (Manhattan, 17 Oct)
        dem, dem_m = ("usgs-3dep-1m", 1.0) if fine else ("usgs-3dep-13", 10.0)
        crs = projected_crs(lidar[0]["zone"]) if lidar else None
        far = "usgs-3dep-13"
    else:
        plan = global_dem.plan(lat, lon, country)
        dem, dem_m, crs, far = plan.near, plan.near_resolution_m, plan.projected_crs, plan.far
    source = aerial.pick(country, lat, lon)
    imagery_m = aerial.SOURCES[source].metres
    return {"id": place["id"], "name": place.get("name", ""), "country": country,
            "terrain": {"source": dem, "name": DEM_NAMES[dem], "resolution_m": dem_m, "far_source": far,
                        "projected_crs": crs, "checked": DEM_CHECKED.get(dem, NOT_YET)},
            "imagery": {"source": source, "name": aerial.SOURCES[source].name, "resolution_m": imagery_m,
                        "licence": aerial.SOURCES[source].licence, "fill": aerial.FALLBACK,
                        "checked": IMAGERY_CHECKED.get(source, NOT_YET)},
            "tier": tier(dem_m, imagery_m)}


def build() -> dict:
    rows = [entry(p) for p in places()]
    return {"schema_version": "1",
            "about": "Generated by scripts/touchdown/place_data_support.py. Tier 'fine' = sub-metre imagery and a DEM "
                     "of 5 m or finer at the landing; 'coarse' otherwise. 'checked' says where each source has been "
                     "fetched for real.",
            "places": rows}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if a.check:
        return 0 if OUT.is_file() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
